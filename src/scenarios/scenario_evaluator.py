def _window_local_step(n_rows: int, T_in: int, T_out: int,
                        T_window: int) -> tuple[np.ndarray, np.ndarray]:
    """
    Shared helper for every scenario-specific metric below.

    scenario_generator.py concatenates many independent T_window-length
    windows back-to-back (see e.g. meta["T_per_window"], usually 104).
    Row i of `pred`/`y_syn` (after the target_arr alignment in
    evaluate_checkpoint) corresponds to absolute target time
    (i + T_in + T_out - 1) in that concatenated series — NOT row i of a
    single window. Any per-window-relative quantity (an event step, a
    failure onset, a breakthrough midpoint) must be computed against
    each row's position WITHIN its own window, not against a single
    global cutoff/midpoint over the whole array. Using a global cutoff
    is exactly the bug that made s3_false_alarm_rate come out as exactly
    0.0 for all 135 checkpoints (see s3_metrics docstring) — the same
    class of bug was independently present in s1_metrics, s2_metrics,
    and s4_metrics, just producing plausible-looking-but-wrong numbers
    instead of an obvious zero, which is why it went unnoticed longer.

    Returns (local_step, window_idx), both shape [n_rows].
    """
    abs_t = np.arange(n_rows) + T_in + T_out - 1
    local_step = abs_t % T_window
    window_idx = abs_t // T_window
    return local_step, window_idx


def s1_metrics(pred: np.ndarray, y_syn: np.ndarray,
               meta: dict, T_in: int, T_out: int) -> dict:
    """
    ConvectiveCell: RMSE at downstream (Cork city) nodes specifically
    during the ~12 steps following the expected flood arrival.

    FIXED: previously sliced pred[arrival:T_eval] as a single global
    cutoff over the whole concatenated array, which only ever evaluated
    the FIRST of the ~21 generation windows' flood arrivals (rows
    ~42-54) and silently discarded the other 20 windows' arrival periods
    entirely — understating both the sample size and, if arrival timing
    or model behaviour varies across windows/seeds, potentially biasing
    the result toward whatever happened to be in that one window. This
    version evaluates the arrival window WITHIN EVERY generation window
    and aggregates across all of them, using the same per-window local
    step recovery as s3_metrics.
    """
    downstream = meta.get("downstream_nodes", [])
    pulse_at   = meta.get("pulse_at_step", 34)
    arrival    = pulse_at + 8    # approximate flood wave arrival at downstream
    T_window   = meta.get("T_per_window", 104)

    if not downstream or pred.shape[0] == 0:
        return {"s1_downstream_rmse": float("nan")}

    n_rows = pred.shape[0]
    local_step, _ = _window_local_step(n_rows, T_in, T_out, T_window)
    # 12-step arrival window, evaluated within EVERY generation window,
    # not just the first.
    in_arrival_window = (local_step >= arrival) & (local_step < arrival + 12)

    if in_arrival_window.sum() < 5:
        return {"s1_downstream_rmse": float("nan")}

    p_down = pred[in_arrival_window][:, downstream]
    t_down = y_syn[in_arrival_window][:, downstream]
    m_down = np.ones_like(p_down, dtype=bool)
    return {
        "s1_downstream_rmse": _rmse(p_down, t_down, m_down),
    }


def s2_metrics(pred: np.ndarray, y_syn: np.ndarray,
               meta: dict, real_rmse: float,
               T_in: int, T_out: int) -> dict:
    """
    GaugeFailure: RMSE after failure onset, both pooled across all nodes
    and restricted specifically to the failed nodes themselves.

    FIXED (time alignment): previously sliced pred[t_fail:] as a single
    global cutoff, which only excludes the first ~36 rows of the ENTIRE
    concatenated array (spanning 40 flood-windows x 3 failure_levels =
    120 segments) rather than isolating genuinely post-failure rows
    WITHIN each of the 120 segments — diluting true post-failure steps
    with pre-failure calm steps from every other segment. This version
    isolates post-failure rows per-window using the same local-step
    recovery as s1/s3_metrics.

    FIXED (node scope): the docstring here previously claimed "RMSE at
    downstream nodes", but the implementation never filtered by node at
    all — it pooled ALL 27 nodes together, meaning the 1-5 nodes whose
    sensor actually failed were diluted among the 22-26 completely
    unaffected nodes in every single evaluation. Even total failure to
    predict the corrupted nodes correctly would barely move a pooled
    27-node RMSE. scenario_generator.py's generate_s2_gauge_failure
    computes failed_node_sets during generation but never saves it to
    meta — this version reconstructs which nodes were failed for any
    given row from the deterministic block ordering
    (row = flood_window_idx * len(failure_levels) + failure_level_idx,
    fail_nodes = headwater_idx[:failure_levels[failure_level_idx]]),
    using headwater_idx and failure_levels, both of which ARE saved.

    Both metrics are reported: s2_post_failure_rmse_all (the original,
    pooled — kept for continuity with prior results) and
    s2_post_failure_rmse_failed_nodes (new, the metric this scenario's
    own docstring already claimed to be computing).
    """
    t_fail    = meta.get("t_failure_step", 36)
    T_window  = meta.get("T_per_window", 104)
    headwater_idx = meta.get("headwater_nodes", [])
    failure_levels = meta.get("failure_levels", [])
    n_rows    = pred.shape[0]

    nan_result = {
        "s2_post_failure_rmse_all": float("nan"),
        "s2_post_failure_rmse_failed_nodes": float("nan"),
        "s2_degradation_ratio": float("nan"),
        "s2_degradation_ratio_failed_nodes": float("nan"),
    }
    if n_rows == 0 or not headwater_idx or not failure_levels:
        return nan_result

    local_step, window_idx = _window_local_step(n_rows, T_in, T_out, T_window)
    is_post = local_step >= t_fail

    if is_post.sum() < 5:
        return nan_result

    # Pooled (original) metric, kept for continuity with prior results.
    p_post = pred[is_post]
    t_post = y_syn[is_post]
    m_post = np.ones_like(p_post, dtype=bool)
    rmse_all = _rmse(p_post, t_post, m_post)

    # Node-restricted metric: build a per-row mask selecting only the
    # nodes actually failed in that row's block.
    n_levels = len(failure_levels)
    node_mask = np.zeros_like(pred, dtype=bool)   # [n_rows, N]
    for w in np.unique(window_idx):
        level_idx = int(w) % n_levels
        n_fail = failure_levels[level_idx]
        fail_nodes = headwater_idx[:n_fail]
        rows_in_window = (window_idx == w)
        node_mask[np.ix_(rows_in_window, fail_nodes)] = True

    combined_mask = node_mask & is_post[:, None]
    if combined_mask.sum() < 5:
        rmse_failed = float("nan")
    else:
        rmse_failed = _rmse(pred, y_syn, combined_mask)

    return {
        "s2_post_failure_rmse_all": rmse_all,
        "s2_post_failure_rmse_failed_nodes": rmse_failed,
        "s2_degradation_ratio": (rmse_all / real_rmse
                                 if real_rmse > 0 and np.isfinite(rmse_all) else float("nan")),
        "s2_degradation_ratio_failed_nodes": (rmse_failed / real_rmse
                                              if real_rmse > 0 and np.isfinite(rmse_failed) else float("nan")),
    }


def s3_metrics(pred: np.ndarray, y_syn: np.ndarray,
               meta: dict, bankfull: np.ndarray,
               T_in: int, T_out: int) -> dict:
    """
    InniscarraRelease: does the model correctly react to a legitimate,
    operationally-driven signal that starts at the reservoir outlet and
    is deliberately decoupled from rainfall — while NOT leaking that
    same signal backward onto the reservoir INFLOW gauges, where it has
    no physical influence (water cannot flow upstream through a dam)?

    scenario_generator.py's S3 changed from a hypothetical debris
    blockage (upstream/downstream stage decoupling on an ordinary river
    edge) to a real, documented ESB reservoir release event. The old
    meta fields ("blockage_edge", "t_blockage_step") no longer exist —
    this version reads the new ones ("release_node", "t_release_step",
    "decoupled_nodes", "downstream_nodes") and reports two
    complementary metrics, both restricted to rows genuinely past each
    window's own release onset (per-window local step via
    _window_local_step — a global cutoff over the concatenated array
    would suffer the same aliasing bug documented in s1/s2_metrics'
    predecessors):

      - s3_downstream_rmse_post: RMSE at the propagation-chain nodes
        downstream of the tailrace during genuinely post-release rows.
        This IS a real, physically-driven signal the model should learn
        to anticipate from the release node's own trajectory, not from
        rainfall. Lower is better.
      - s3_upstream_leakage_bias: mean(pred - obs) at the two reservoir
        INFLOW nodes (Inniscarra Headrace, Carrigadrohid Headrace)
        during the same rows. These nodes carry no synthetic
        perturbation at all — obs stays at its natural pre-release
        level — so any systematic rise here is the model spuriously
        routing an outlet-driven signal backward against the hydraulic
        gradient. Should be ~0 for any model that respects reservoir
        topology; a large positive value is the direct analogue of the
        old scenario's "false alarm".
    """
    release    = meta.get("release_node", {})
    t_rel      = meta.get("t_release_step", 36)
    T_window   = meta.get("T_per_window", 104)
    downstream = meta.get("downstream_nodes", [])
    decoupled  = meta.get("decoupled_nodes", {})
    decoupled_idx = [v["idx"] for v in decoupled.values()] if decoupled else []

    if not downstream or pred.shape[0] == 0:
        return {"s3_downstream_rmse_post": float("nan"),
                "s3_upstream_leakage_bias": float("nan")}

    n_rows = pred.shape[0]
    local_step, _ = _window_local_step(n_rows, T_in, T_out, T_window)
    is_post = local_step >= t_rel

    if is_post.sum() < 5:
        return {"s3_downstream_rmse_post": float("nan"),
                "s3_upstream_leakage_bias": float("nan")}

    p_down = pred[is_post][:, downstream]
    t_down = y_syn[is_post][:, downstream]
    m_down = np.ones_like(p_down, dtype=bool)
    downstream_rmse = _rmse(p_down, t_down, m_down)

    if decoupled_idx:
        p_up = pred[is_post][:, decoupled_idx]
        t_up = y_syn[is_post][:, decoupled_idx]
        finite = np.isfinite(p_up) & np.isfinite(t_up)
        leakage_bias = (float(np.mean((p_up - t_up)[finite]))
                        if finite.sum() > 0 else float("nan"))
    else:
        leakage_bias = float("nan")

    return {
        "s3_downstream_rmse_post": (round(downstream_rmse, 5)
                                    if np.isfinite(downstream_rmse) else float("nan")),
        "s3_upstream_leakage_bias": (round(leakage_bias, 5)
                                     if np.isfinite(leakage_bias) else float("nan")),
    }


def s4_metrics(pred: np.ndarray, y_syn: np.ndarray,
               X_syn: np.ndarray, meta: dict,
               T_in: int, T_out: int) -> dict:
    """
    SatBreakthrough: RMSE before and after breakthrough, plus ratio.
    Models that correctly anticipate the breakthrough should have
    lower post-breakthrough RMSE relative to their pre-breakthrough RMSE.

    FIXED: previously used t_bt = T // 2 — the midpoint of the ENTIRE
    concatenated array (30 generation windows x 104 steps = 3120 rows).
    That midpoint (row 1560) falls exactly on a window boundary, so
    rmse_pre was actually computed over windows 0-14 IN THEIR ENTIRETY
    (mixing each window's true pre- AND post-breakthrough segments
    together) and rmse_post over windows 15-29 entirely — this has
    nothing to do with sat_breakthrough_step (meta["sat_breakthrough_step"],
    typically 46 steps into each window — see scenario_generator.py's
    derivation of sat_breakthrough_step from the saturation ramp
    parameters, fixed from an earlier hardcoded T_IN+8 that didn't
    actually coincide with the ramp crossing its own excess_factor
    threshold), despite producing plausible-looking, non-zero numbers.
    This version isolates pre/post-breakthrough rows WITHIN every window
    using the same local-step recovery as s1/s2/s3_metrics.
    """
    t_bt      = meta.get("sat_breakthrough_step", 46)
    T_window  = meta.get("T_per_window", 104)
    n_rows    = pred.shape[0]

    if n_rows == 0:
        return {"s4_rmse_pre_breakthrough":  float("nan"),
                "s4_rmse_post_breakthrough": float("nan"),
                "s4_post_pre_ratio":         float("nan")}

    local_step, _ = _window_local_step(n_rows, T_in, T_out, T_window)
    is_pre  = local_step <  t_bt
    is_post = local_step >= t_bt

    if is_pre.sum() < 5 or is_post.sum() < 5:
        return {"s4_rmse_pre_breakthrough":  float("nan"),
                "s4_rmse_post_breakthrough": float("nan"),
                "s4_post_pre_ratio":         float("nan")}

    mask_a = np.ones((is_pre.sum(),  pred.shape[1]), dtype=bool)
    mask_b = np.ones((is_post.sum(), pred.shape[1]), dtype=bool)
    rmse_pre  = _rmse(pred[is_pre],  y_syn[is_pre],  mask_a)
    rmse_post = _rmse(pred[is_post], y_syn[is_post], mask_b)
    return {
        "s4_rmse_pre_breakthrough":  rmse_pre,
        "s4_rmse_post_breakthrough": rmse_post,
        "s4_post_pre_ratio":         (rmse_post / max(rmse_pre, 1e-6)),
    }


def s6_metrics(pred: np.ndarray, y_syn: np.ndarray,
               meta: dict, T_in: int, T_out: int) -> dict:
    """
    ChannelBlockage: quantifies the architectural blind spot at the
    bridge/culvert backwater location, rather than testing whether a
    model "passes." A large positive s6_upstream_backwater_bias is the
    EXPECTED result for every model — see generate_s6_channel_blockage's
    docstring in scenario_generator.py for why no model in this suite
    has a message-passing pathway to anticipate it.

      - s6_upstream_backwater_bias: mean(obs - pred) at the
        blockage+upstream nodes during genuinely post-blockage rows.
        Positive = model under-predicts the backwater rise it can't see
        coming (the expected failure mode). Near zero would mean the
        model somehow anticipated it, worth investigating why.
      - s6_downstream_suppression_rmse: RMSE at the immediate downstream
        node during the same rows — this one IS potentially learnable
        from the node's own upstream-of-it inputs (rainfall, its own
        recent stage trend) without needing reverse graph edges, so
        unlike the backwater metric, better performance here is a
        real, meaningful comparison across models.

    Uses the same per-window local-step recovery as s1-s4_metrics (see
    _window_local_step) — a global cutoff over the concatenated array
    would misattribute rows across window boundaries.
    """
    blockage = meta.get("blockage_node", {})
    upstream = meta.get("upstream_node", {})
    downstream = meta.get("downstream_node", {})
    t_blk    = meta.get("t_blockage_step", 36)
    T_window = meta.get("T_per_window", 104)

    backwater_idx = [i for i in (blockage.get("idx"), upstream.get("idx"))
                     if i is not None]
    downstream_idx = downstream.get("idx")

    if not backwater_idx or downstream_idx is None or pred.shape[0] == 0:
        return {"s6_upstream_backwater_bias": float("nan"),
                "s6_downstream_suppression_rmse": float("nan")}

    n_rows = pred.shape[0]
    local_step, _ = _window_local_step(n_rows, T_in, T_out, T_window)
    is_post = local_step >= t_blk

    if is_post.sum() < 5:
        return {"s6_upstream_backwater_bias": float("nan"),
                "s6_downstream_suppression_rmse": float("nan")}

    p_bw = pred[is_post][:, backwater_idx]
    t_bw = y_syn[is_post][:, backwater_idx]
    finite = np.isfinite(p_bw) & np.isfinite(t_bw)
    bias = float(np.mean((t_bw - p_bw)[finite])) if finite.sum() > 0 else float("nan")

    p_down = pred[is_post][:, [downstream_idx]]
    t_down = y_syn[is_post][:, [downstream_idx]]
    m_down = np.ones_like(p_down, dtype=bool)
    down_rmse = _rmse(p_down, t_down, m_down)

    return {
        "s6_upstream_backwater_bias": round(bias, 5) if np.isfinite(bias) else float("nan"),
        "s6_downstream_suppression_rmse": (round(down_rmse, 5)
                                           if np.isfinite(down_rmse) else float("nan")),
    }


def s5_metrics(pred: np.ndarray, y_syn: np.ndarray,
               meta: dict) -> dict:
    """
    SpatialGradient: RMSE specifically at the most downstream (eastern) nodes,
    where graph routing is required to carry the western flood signal.
    """
    downstream = meta.get("downstream_nodes", [])
    if not downstream:
        return {"s5_downstream_rmse": float("nan")}
    p_d = pred[:, downstream]
    t_d = y_syn[:, downstream]
    m_d = np.ones_like(p_d, dtype=bool)
    return {"s5_downstream_rmse": _rmse(p_d, t_d, m_d)}


# ══════════════════════════════════════════════════════════════════════════════
# Core inference on synthetic array
# ══════════════════════════════════════════════════════════════════════════════

@torch.no_grad()
def run_on_scenario(
    model:    torch.nn.Module,
    tag:      str,
    hp:       dict,
    X_syn:    np.ndarray,   # [T_s, N, F]
    y_syn:    np.ndarray,   # [T_s, N]
    m_syn:    np.ndarray,   # [T_s, N]
    T_in:     int,
    T_out:    int,
    device:   torch.device,
) -> np.ndarray:
    """
    Slide a T_in-step window over the synthetic time series, run the model
    forward, and return predictions at step T_out-1 as [n_windows, N].
    """
    ei, ea, na = load_graph(device)

    needs_graph = tag not in ("gru", "lstm", "ealstm", "dfc_gnn", "dfc_gnn_unified")
    if not needs_graph:
        ei, ea = None, None
    if tag in ("dfc_gnn", "dfc_gnn_unified"):
        na = None

    T_s = X_syn.shape[0]
    N   = X_syn.shape[1]
    F   = X_syn.shape[2]

    # Build node_attr tensor (z-score using real dataset stats for consistency)
    import pandas as _pd
    nd_df = pd.read_csv(GRAPH_DIR / "nodes.csv")
    node_cols = ["log_catchment_area_km2", "gauge_datum_mOSGM15", "p90_mAOD",
                 "amax_med_mAOD", "is_reservoir", "is_tidal", "has_discharge"]
    na_raw = torch.tensor(nd_df[node_cols].values, dtype=torch.float32)
    na_real = (na_raw - na_raw.mean(0)) / na_raw.std(0).clamp(min=1e-6)
    if na is not None:
        na = na_real.to(device)

    preds = []
    stride = 1
    for t in range(0, T_s - T_in - T_out + 1, stride):
        x_np   = X_syn[t : t + T_in]          # [T_in, N, F]
        x_t    = torch.tensor(x_np, dtype=torch.float32).unsqueeze(0).to(device)
        # x_t: [1, T_in, N, F]

        if tag in ("dfc_gnn", "dfc_gnn_unified"):
            output = model(x_t)
            delta  = output[0] if isinstance(output, (tuple, list)) else output
        elif needs_graph:
            delta = model(x_t, na, ei, ea)
        else:
            delta = model(x_t, na)

        last_obs = x_t[:, -1, :, F_STAGE]         # [1, N]
        abs_pred = delta[:, T_out - 1, :] + last_obs  # [1, N]
        preds.append(abs_pred.detach().cpu().numpy()[0])  # [N]

    return np.stack(preds, axis=0) if preds else np.zeros((0, N))


