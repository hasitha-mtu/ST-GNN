# Per-checkpoint evaluation
# ══════════════════════════════════════════════════════════════════════════════

def evaluate_checkpoint(ckpt_dir: Path, scen_dir: Path,
                        device: torch.device,
                        bankfull: np.ndarray) -> dict | None:
    """
    Load one checkpoint, run it on the synthetic scenario, compute metrics.
    Returns a flat dict of results suitable for a CSV row.
    """
    tag = resolve_model_tag(ckpt_dir)
    rel = ckpt_dir.relative_to(CKPT_ROOT)
    parts = rel.parts
    if len(parts) < 3:
        return None
    try:
        seed   = int(parts[1])
        T_out  = int(parts[2])
    except (ValueError, IndexError):
        return None

    # Load scenario arrays
    X_syn = np.load(scen_dir / "X_synthetic.npy")
    y_syn = np.load(scen_dir / "y_synthetic.npy")
    m_syn = np.load(scen_dir / "mask_synthetic.npy")
    with open(scen_dir / "scenario_meta.json") as f:
        meta = json.load(f)

    # Load model weights
    try:
        model, hp = load_model(ckpt_dir, device)
    except Exception as e:
        print(f"    [skip] load_model failed for {ckpt_dir.name}: {e}")
        return None

    T_in = hp.get("t_in", 32)

    try:
        pred = run_on_scenario(
            model, tag, hp, X_syn, y_syn, m_syn,
            T_in=T_in, T_out=T_out, device=device)
    except Exception as e:
        print(f"    [skip] inference failed: {e}")
        return None

    # Guard against scenarios shorter than this checkpoint's T_in+T_out
    # requirement. run_on_scenario() already returns an empty (0, N) array
    # in that case rather than raising — but without this check, the
    # np.stack() calls below crash with "need at least one array to
    # stack", and since this whole function is called from main() with no
    # surrounding try/except, that crash kills the ENTIRE sweep instead of
    # skipping just this one (model, seed, horizon) combination.
    n_windows = pred.shape[0]
    if n_windows == 0:
        min_len_needed = T_in + T_out
        print(f"    [skip] scenario series too short for this checkpoint: "
              f"needs >= {min_len_needed} steps (T_in={T_in} + T_out={T_out}), "
              f"got {len(y_syn)} steps in {scen_dir.name}")
        return None

    # Align predictions to targets
    # Target: y at T_out-1 steps ahead of each window start
    target_arr = np.stack([
        y_syn[t + T_in + T_out - 1]
        for t in range(n_windows)
        if t + T_in + T_out - 1 < len(y_syn)
    ], axis=0)  # [n_windows, N]
    mask_arr = np.stack([
        m_syn[t + T_in + T_out - 1]
        for t in range(n_windows)
        if t + T_in + T_out - 1 < len(y_syn)
    ], axis=0)

    # Second guard: n_windows > 0 doesn't guarantee the filtered list above
    # is non-empty — e.g. if T_in/T_out reported by run_on_scenario ever
    # drifted out of sync with the T_in/T_out used inside this function
    # (they shouldn't, since both come from the same hp/T_out, but this
    # keeps the two np.stack() calls from being the only thing standing
    # between a subtle inconsistency and a full-sweep crash).
    if target_arr.shape[0] == 0:
        print(f"    [skip] no valid (window, target) pairs after alignment "
              f"for {scen_dir.name}")
        return None

    pred = pred[:len(target_arr)]
    # Global metrics on synthetic data
    nse  = _nse(pred,  target_arr, mask_arr)
    rmse = _rmse(pred, target_arr, mask_arr)
    pod, far = _pod_far(pred, target_arr, bankfull)
    extended = compute_scenario_extended_metrics(
        pred, target_arr, mask_arr, bankfull, meta, T_in, T_out)

    # Real-data RMSE for degradation ratio
    real_rmse = float("nan")
    real_metrics_path = ckpt_dir / "test_metrics.json"
    if real_metrics_path.exists():
        with open(real_metrics_path) as f:
            real_rmse = float(json.load(f).get("rmse", float("nan")))

    result = {
        "scenario":   meta["name"],
        "model":      tag,
        "seed":       seed,
        "horizon":    T_out,
        "nse_syn":    round(nse,  4) if np.isfinite(nse)  else None,
        "rmse_syn":   round(rmse, 4) if np.isfinite(rmse) else None,
        "pod_syn":    round(pod,  4),
        "far_syn":    round(far,  4),
        "real_rmse":  round(real_rmse, 4) if np.isfinite(real_rmse) else None,
        "degradation_ratio": round(rmse / real_rmse, 3)
            if (np.isfinite(rmse) and np.isfinite(real_rmse) and real_rmse > 0)
            else None,
        **extended,
    }

    # Scenario-specific extras
    scen_id = meta["name"][:2]
    if scen_id == "S1":
        result.update(s1_metrics(pred, target_arr, meta, T_in, T_out))
    elif scen_id == "S2":
        result.update(s2_metrics(pred, target_arr, meta, real_rmse, T_in, T_out))
    elif scen_id == "S3":
        result.update(s3_metrics(pred, target_arr, meta, bankfull, T_in, T_out))
    elif scen_id == "S4":
        result.update(s4_metrics(pred, target_arr, X_syn, meta, T_in, T_out))
    elif scen_id == "S5":
        result.update(s5_metrics(pred, target_arr, meta))
    elif scen_id == "S6":
        result.update(s6_metrics(pred, target_arr, meta, T_in, T_out))

    return result


# ══════════════════════════════════════════════════════════════════════════════
# Main
# ══════════════════════════════════════════════════════════════════════════════

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Evaluate trained models on synthetic scenarios")
    parser.add_argument("--all-scenarios", action="store_true")
    parser.add_argument("--all-models",    action="store_true")
    parser.add_argument("--scenario",  type=str, default=None,
                        help="Scenario name or ID (e.g. S1, S1_ConvectiveCell)")
    parser.add_argument("--model",     type=str, default=None,
                        help="Model tag (e.g. gru, st_gnn_hand_edge)")
    parser.add_argument("--horizon",   type=int, default=None,
                        help="Evaluate only this T_out horizon")
    parser.add_argument("--force",     action="store_true",
                        help="Re-evaluate even if results already exist")
    args = parser.parse_args()

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")

    # Determine which scenarios to run
    if args.all_scenarios:
        scen_names = SCENARIOS
    elif args.scenario:
        # Accept short form (S1) or full name
        scen_names = [s for s in SCENARIOS
                      if s.startswith(args.scenario) or
                      s == args.scenario]
        if not scen_names:
            print(f"Unknown scenario '{args.scenario}'. "
                  f"Available: {SCENARIOS}")
            return
    else:
        parser.error("Specify --all-scenarios or --scenario NAME")

    # Load bankfull thresholds
    with open(GRAPH_DIR / "bankfull_thresholds.json") as f:
        bf_raw = json.load(f)
    bf_dict = bf_raw.get("thresholds", bf_raw)
    import pandas as pd
    nd = pd.read_csv(GRAPH_DIR / "nodes.csv")
    refs = [str(r) for r in nd["ref"].tolist()]
    bankfull = np.array([float(bf_dict.get(r, 0.5)) for r in refs],
                        dtype=np.float32)

    # Collect checkpoints
    all_ckpts = find_leaf_checkpoints(CKPT_ROOT)
    if args.model:
        all_ckpts = [c for c in all_ckpts
                     if resolve_model_tag(c) == args.model]
    if args.horizon:
        all_ckpts = [c for c in all_ckpts
                     if c.name == str(args.horizon)]
    print(f"Checkpoints to evaluate: {len(all_ckpts)}")

    all_rows: list[dict] = []

    for scen_name in scen_names:
        scen_dir = SCEN_DIR / scen_name
        if not (scen_dir / "X_synthetic.npy").exists():
            print(f"\n[skip] {scen_name}: scenario data not found. "
                  f"Run scenario_generator.py first.")
            continue

        print(f"\n{'='*55}")
        print(f"Evaluating: {scen_name}  ({len(all_ckpts)} checkpoints)")
        print(f"{'='*55}")

        scen_results_dir = RESULTS / scen_name
        scen_results_dir.mkdir(parents=True, exist_ok=True)
        rows = []

        for i, ckpt_dir in enumerate(all_ckpts):
            tag   = resolve_model_tag(ckpt_dir)
            rel   = ckpt_dir.relative_to(CKPT_ROOT)
            label = str(rel)

            # Cache check
            cache_path = scen_results_dir / f"{label.replace('/', '_')}.json"
            if cache_path.exists() and not args.force:
                with open(cache_path) as f:
                    row = json.load(f)
                rows.append(row)
                continue
            print(f"  [{i+1:3d}/{len(all_ckpts)}] {label} … ", end="", flush=True)
            try:
                print('evaluating checkpoints...')
                row = evaluate_checkpoint(ckpt_dir, scen_dir, device, bankfull)
            except Exception as e:
                # Belt-and-braces: evaluate_checkpoint() already catches
                # the failure modes we know about (model load, inference,
                # empty-window alignment) and returns None for those. This
                # catches anything else so one bad checkpoint can't take
                # down the remaining ~130 in the sweep.
                print(f"FAILED (unhandled: {type(e).__name__}: {e})")
                row = None
            if row:
                rows.append(row)
                all_rows.append(row)
                cache_path.parent.mkdir(parents=True, exist_ok=True)
                with open(cache_path, "w") as f:
                    json.dump(row, f)
                print(f"NSE={row.get('nse_syn', 'nan'):.4f}  "
                      f"RMSE={row.get('rmse_syn', 'nan'):.4f}")
            else:
                print("FAILED")

        # Save per-scenario results
        if rows:
            df_scen = pd.DataFrame(rows)
            df_scen.to_csv(scen_results_dir / "model_metrics.csv", index=False)
            print(f"  Saved: {scen_results_dir / 'model_metrics.csv'} "
                  f"({len(rows)} rows)")

    # Save consolidated CSV
    if all_rows:
        df_all = pd.DataFrame(all_rows)
        out_csv = RESULTS / "scenario_summary.csv"
        df_all.to_csv(out_csv, index=False)
        print(f"\nConsolidated: {out_csv} ({len(all_rows)} rows)")


if __name__ == "__main__":
    main()
